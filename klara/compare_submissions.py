"""Compare test predictions without claiming accuracy when labels are absent."""
from pathlib import Path
import json
import pandas as pd
from src.prediction import validate_submission
R=Path(__file__).resolve().parent
ours=pd.read_csv(R/'submission.csv',dtype={'prediction':str})
other=pd.read_csv(R.parent.parent/'submission.csv',dtype={'prediction':str})
test=pd.read_csv(R.parent/'test.csv')
validate_submission(test,ours); validate_submission(test,other)
d=ours.merge(other,on='sample_id',suffixes=('_ours','_colleague'),validate='one_to_one')
a=d.prediction_ours.str.split().map(lambda v:list(map(int,v)))
b=d.prediction_colleague.str.split().map(lambda v:list(map(int,v)))
d['same_top1']=[x[0]==y[0] for x,y in zip(a,b)]
d['shared_top3']=[len(set(x)&set(y)) for x,y in zip(a,b)]
d['same_top3_set']=d.shared_top3.eq(3)
d['same_order']=[x==y for x,y in zip(a,b)]
d=d.merge(test[['sample_id','session','atco']].drop_duplicates(),on='sample_id',validate='one_to_one')
summary={'samples':len(d),'both_submissions_valid':True,'labelled_overlap':{},'same_top1_count':int(d.same_top1.sum()),'same_top1_fraction':float(d.same_top1.mean()),'same_top3_set_count':int(d.same_top3_set.sum()),'same_top3_set_fraction':float(d.same_top3_set.mean()),'same_order_count':int(d.same_order.sum()),'mean_shared_top3':float(d.shared_top3.mean()),'shared_top3_counts':{int(k):int(v) for k,v in d.shared_top3.value_counts().sort_index().items()},'accuracy_comparison_possible':False}
for split in ['train','validation']:
 ids=pd.read_csv(R.parent/f'{split}.csv',usecols=['sample_id']).sample_id
 summary['labelled_overlap'][split]=len(set(ids)&set(d.sample_id))
by=d.groupby(['session','atco']).agg(samples=('sample_id','size'),same_top1_fraction=('same_top1','mean'),same_top3_set_fraction=('same_top3_set','mean'),mean_shared_top3=('shared_top3','mean')).reset_index()
out=R/'outputs'/'colleague_comparison'; out.mkdir(exist_ok=True)
d.to_csv(out/'sample_comparison.csv',index=False); by.to_csv(out/'session_comparison.csv',index=False); (out/'summary.json').write_text(json.dumps(summary,indent=2))
text=f'''# Comparison with colleague's submission

Both files are valid predictions for the same {len(d)} unlabelled test snapshots. Neither contains predictions for labelled train or validation snapshots. Consequently, their accuracy and which model is better cannot be determined from these files.

- Same top-3 set: {d.same_top3_set.sum()} / {len(d)} ({d.same_top3_set.mean():.2%}). These samples receive exactly the same competition score regardless of prediction order.
- Different top-3 sets: {(~d.same_top3_set).sum()} / {len(d)}. Outcomes require true labels.
- Same first choice: {d.same_top1.sum()} / {len(d)} ({d.same_top1.mean():.2%}).
- Mean shared candidates among top 3: {d.shared_top3.mean():.3f}.

These are agreement statistics, not accuracy scores. Our model's known official-validation top-3 is 61.42%, but the colleague's test predictions cannot be compared against that score.

For a fair accuracy comparison, obtain the colleague's predictions on validation.csv generated by a model trained only on train.csv, or their code/model trained without validation labels. If their model used train + validation, evaluating that model on validation would leak labels. Matching controller-held-out predictions would provide a stronger comparison.
'''
(out/'comparison.md').write_text(text)
print(json.dumps(summary,indent=2)); print(by.to_string(index=False))
